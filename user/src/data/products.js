// Utility functions
export function getProductById(id) {
  return products.find(p => p.id === id);
}

export function getProductsByCategory(categoryId) {
  return products.filter(p => p.category === categoryId);
}

export function getProductsBySubcategory(categoryId, subcategoryId) {
  return products.filter(p => p.category === categoryId && p.subcategory === subcategoryId);
}

export function searchProducts(query) {
  const q = query.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.partNumber.toLowerCase().includes(q) ||
    p.manufacturer.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q)
  );
}

export function getStockStatus(stock) {
  if (stock >= 1000) return { label: 'In Stock', class: 'in-stock' };
  if (stock > 0) return { label: 'Low Stock', class: 'low-stock' };
  return { label: 'Out of Stock', class: 'out-of-stock' };
}

export function formatStock(stock) {
  if (stock >= 1000000) return `${(stock / 1000000).toFixed(1)}M`;
  if (stock >= 1000) return `${(stock / 1000).toFixed(0)}K+`;
  return stock.toString();
}

